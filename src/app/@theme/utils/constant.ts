export const getCountryCodeList = (): any[] => {
  return country.map((i) => {
    return { callingCode: i.callingCode, code: i.code };
  });
};
export const getCountryCode = (name): string => {
  return country.find((i) => i.name == name).callingCode;
};

export const getCountryList = (): IOption[] => {
  return country.map((itm) => ({ text: itm.name, value: itm.name }));
};

export const getCountryThroughCode = (callingCode: string): string => {
  return country.find((itm) => itm.callingCode === callingCode).name;
};

export const getCountryCodeThroughCallingCode = (
  callingCode: string
): string => {
  return country.find((itm) => itm?.callingCode === callingCode).code;
};

